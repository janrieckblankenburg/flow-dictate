#!/bin/zsh
# Build /Applications/Flow Dictate.app and install the LaunchAgent.
#
# WHY THIS EXISTS
# The bundle, its launcher and the LaunchAgent used to exist only as files on
# one disk, with no record of the codesign invocation that produced them. That
# made the recovery procedure for a Python upgrade impossible to reconstruct.
#
# WHAT IT FIXES vs. the hand-built bundle
#   1. The executable sits directly in Contents/MacOS/, so Info.plist actually
#      applies. In the old layout the launcher exec'd Contents/MacOS/runtime/…,
#      one level too deep for CFBundle to find Contents/Info.plist — which is
#      why NSMicrophoneUsageDescription never appeared in the permission
#      prompt, why LSUIElement did nothing, and why the app had to set its
#      activation policy and icon by hand at runtime.
#   2. The Python version is discovered, not hardcoded. The old launcher had
#      python3.11 baked into PYTHONPATH, so a 3.12 upgrade turned into a
#      restart loop.
#   3. It fails loudly. Every step is checked instead of leaving a half-built
#      bundle that launches and then dies on an import.
#
# ONE-TIME COST: re-signing changes the bundle's code identity, so macOS treats
# it as a new program and REVOKES Microphone, Input Monitoring and
# Accessibility. You must re-grant all three afterwards (see the reminder the
# script prints at the end).
#
# Usage:  ./install.sh            build + install
#         ./install.sh --no-agent build the bundle only

set -euo pipefail

APP_HOME="${0:A:h}"
APP="/Applications/Flow Dictate.app"
LABEL="com.hdt.flow-dictate"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
INSTALL_AGENT=1
[[ "${1:-}" == "--no-agent" ]] && INSTALL_AGENT=0

die() { print -u2 "error: $*"; exit 1 }

# ── Preflight ────────────────────────────────────────────────────────
[[ -f "$APP_HOME/dictate.py" ]] || die "run this from the flow-dictate folder"
[[ -d "$APP_HOME/.venv" ]] || die "no .venv — run ./setup.sh first"

VENV_PY="$APP_HOME/.venv/bin/python"
[[ -x "$VENV_PY" ]] || die "$VENV_PY is missing or not executable"

# Ask the interpreter rather than guessing: this is what the old launcher got
# wrong by hardcoding python3.11.
PY_TAG=$("$VENV_PY" -c 'import sys; print(f"python{sys.version_info.major}.{sys.version_info.minor}")')
SITE="$APP_HOME/.venv/lib/$PY_TAG/site-packages"
[[ -d "$SITE" ]] || die "site-packages not found at $SITE"

# The GUI-capable binary — NOT .venv/bin/python, which is a stub that re-execs
# and would leave the wrong process identity in permission dialogs.
REAL_PY=$("$VENV_PY" -c '
import sys, pathlib
base = pathlib.Path(sys.base_prefix)
cand = base / "Resources" / "Python.app" / "Contents" / "MacOS" / "Python"
print(cand if cand.exists() else sys.executable)')
[[ -f "$REAL_PY" ]] || die "could not locate the GUI Python binary ($REAL_PY)"

"$VENV_PY" - <<'PYEOF' || die "dependencies are incomplete — re-run ./setup.sh"
import sys
missing = []
for mod in ("numpy", "sounddevice", "pynput", "mlx_whisper", "rumps",
            "AppKit", "Quartz", "Foundation"):
    try:
        __import__(mod)
    except Exception as e:
        missing.append(f"{mod} ({e.__class__.__name__})")
if missing:
    print("missing:", ", ".join(missing), file=sys.stderr)
    sys.exit(1)
PYEOF

print "Python:       $PY_TAG"
print "GUI binary:   $REAL_PY"
print "site-packages: $SITE"
print

# ── Build the bundle ─────────────────────────────────────────────────
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# The launcher IS CFBundleExecutable and lives directly in Contents/MacOS, so
# the bundle resolves correctly from it.
cat > "$APP/Contents/MacOS/Flow Dictate" <<LAUNCHER
#!/bin/zsh
# Generated by install.sh — edit that, not this.
APP_HOME="$APP_HOME"
cd "\$APP_HOME" || { print -u2 "Flow Dictate: \$APP_HOME is gone"; exit 1 }
[[ -f .env ]] && { set -a; source .env; set +a }
export PYTHONPATH="$SITE"
export PYTHONNOUSERSITE=1
exec "\$0:A:h/python-runtime" -u "\$APP_HOME/dictate.py"
LAUNCHER
chmod +x "$APP/Contents/MacOS/Flow Dictate"

cp "$REAL_PY" "$APP/Contents/MacOS/python-runtime"
chmod +x "$APP/Contents/MacOS/python-runtime"

[[ -f "$APP_HOME/AppIcon.icns" ]] && cp "$APP_HOME/AppIcon.icns" "$APP/Contents/Resources/"

cat > "$APP/Contents/Info.plist" <<'PLISTEOF'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDisplayName</key><string>Flow Dictate</string>
	<key>CFBundleExecutable</key><string>Flow Dictate</string>
	<key>CFBundleIconFile</key><string>AppIcon</string>
	<key>CFBundleIdentifier</key><string>com.hdt.flow-dictate</string>
	<key>CFBundleName</key><string>Flow Dictate</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleShortVersionString</key><string>1.1.0</string>
	<key>CFBundleVersion</key><string>2</string>
	<key>LSMinimumSystemVersion</key><string>12.0</string>
	<key>LSUIElement</key><true/>
	<key>NSHighResolutionCapable</key><true/>
	<key>NSMicrophoneUsageDescription</key>
	<string>Flow Dictate records your voice while you hold the fn key and transcribes it locally on this Mac.</string>
	<!-- mlx is Apple-Silicon only. Without this the app would launch under
	     Rosetta on an Intel Mac and fail mid-import instead of at launch. -->
	<key>LSArchitecturePriority</key><array><string>arm64</string></array>
</dict>
</plist>
PLISTEOF

# Sign with an explicit identifier. If a self-signed code-signing identity
# named "Flow Dictate Signing" exists in the login keychain it is used, which
# gives the bundle a STABLE identity so permissions survive a rebuild.
# Otherwise fall back to ad-hoc, where the identity is a hash of the binary and
# every rebuild revokes permissions again.
IDENTITY=$(security find-identity -v -p codesigning 2>/dev/null \
           | grep -o '"Flow Dictate Signing"' | head -1 | tr -d '"' || true)
if [[ -n "$IDENTITY" ]]; then
  print "Signing with \"$IDENTITY\" (stable identity — permissions persist)"
  codesign --force --sign "$IDENTITY" --identifier "$LABEL" "$APP" \
    || die "codesign failed"
else
  print "Signing ad-hoc (no \"Flow Dictate Signing\" identity found)."
  print "  Permissions will need re-granting after every rebuild. To fix that"
  print "  permanently, create a self-signed Code Signing certificate named"
  print "  \"Flow Dictate Signing\" in Keychain Access, then re-run this script."
  codesign --force --sign - --identifier "$LABEL" "$APP" || die "codesign failed"
fi
codesign --verify --deep --strict "$APP" || die "the signed bundle does not verify"

# ── LaunchAgent ──────────────────────────────────────────────────────
if (( INSTALL_AGENT )); then
  mkdir -p "$HOME/Library/LaunchAgents"
  cat > "$PLIST" <<AGENTEOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>Label</key><string>$LABEL</string>
	<key>ProgramArguments</key>
	<array><string>$APP/Contents/MacOS/Flow Dictate</string></array>
	<key>RunAtLoad</key><true/>
	<key>ProcessType</key><string>Interactive</string>
	<key>AssociatedBundleIdentifiers</key><array><string>$LABEL</string></array>
	<key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
	<!-- Without a throttle, a startup failure respawns every 10s forever and
	     writes a full banner each time — megabytes of log per day. -->
	<key>ThrottleInterval</key><integer>60</integer>
	<key>StandardOutPath</key><string>$APP_HOME/flow-dictate.log</string>
	<key>StandardErrorPath</key><string>$APP_HOME/flow-dictate.log</string>
</dict>
</plist>
AGENTEOF
  launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$PLIST" || die "launchctl bootstrap failed"
  print "LaunchAgent installed and started."
fi

print
print "Done. $APP"
print
print "Because the code signature changed, macOS has revoked these — re-grant"
print "them in System Settings > Privacy & Security:"
print "  1. Microphone        (prompted on the first dictation)"
print "  2. Input Monitoring  (for the global fn hotkey)"
print "  3. Accessibility     (to send Cmd-V into other apps)"
print
print "Then check it came up:  tail -f $APP_HOME/flow-dictate.log"
